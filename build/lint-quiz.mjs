// lint-quiz.mjs — catch quizzes that can be passed without knowing anything.
//
// usage: node build/lint-quiz.mjs [tech ...]        (default: every ship)
//        node build/lint-quiz.mjs --strict          (exit 1 on any failure)
//        node build/lint-quiz.mjs --list            (print every offending question)
//
// Two failure modes are checked, both measured against a naive test-taker:
//   POSITION — can you pass by always pressing the same letter?
//   LENGTH   — can you pass by always picking the longest option?
// A question whose correct answer is a paragraph and whose distractors are
// two-word stubs teaches nothing; it tests reading speed.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const STRICT = args.includes('--strict');
const LIST = args.includes('--list');
const only = args.filter(a => !a.startsWith('--'));

// thresholds — a real 4-option quiz should sit near 25% on both heuristics
const MAX_POSITION_RATE = 0.45;   // "always press the same letter" success
const MAX_LENGTH_RATE = 0.45;     // "always pick the longest" success
const MAX_LENGTH_RATIO = 1.6;     // correct answer vs mean distractor, per question
const MIN_DISTRACTOR = 40;        // chars — shorter than this reads as a placeholder
const PASS_MARK = 70;             // must match the engine

export function loadQuiz(tech) {
  const file = path.join(ROOT, 'data', tech + '.js');
  if (!fs.existsSync(file)) return null;
  const src = fs.readFileSync(file, 'utf8');
  const sandbox = { window: {} };
  new Function('window', src).call(sandbox, sandbox.window);
  return sandbox.window.SHIPYARD_DATA;
}

export function auditQuiz(quiz) {
  const items = [];
  for (const [pid, questions] of Object.entries(quiz || {})) {
    questions.forEach((q, i) => items.push({ pid, i, q }));
  }
  const n = items.length;
  const posCount = {};
  let longestHits = 0;
  const offenders = [];

  for (const it of items) {
    const { q } = it;
    posCount[q.a] = (posCount[q.a] || 0) + 1;

    let longest = 0;
    q.o.forEach((o, j) => { if (o.length > q.o[longest].length) longest = j; });
    if (longest === q.a) longestHits++;

    const correctLen = q.o[q.a].length;
    const distractors = q.o.filter((_, j) => j !== q.a);
    const meanDistractor = distractors.reduce((s, o) => s + o.length, 0) / (distractors.length || 1);
    const ratio = meanDistractor ? correctLen / meanDistractor : Infinity;
    const shortest = Math.min(...distractors.map(o => o.length));

    const reasons = [];
    if (ratio > MAX_LENGTH_RATIO) reasons.push(`answer ${ratio.toFixed(1)}x longer than distractors`);
    if (shortest < MIN_DISTRACTOR) reasons.push(`shortest distractor ${shortest} chars`);
    if (reasons.length) offenders.push({ ...it, reasons, ratio, shortest });
  }

  const topPos = Object.entries(posCount).sort((a, b) => b[1] - a[1])[0] || ['0', 0];
  return {
    n,
    positionRate: n ? topPos[1] / n : 0,
    positionLetter: String.fromCharCode(65 + Number(topPos[0])),
    positionSpread: posCount,
    lengthRate: n ? longestHits / n : 0,
    offenders,
  };
}

function report(tech, data) {
  const r = auditQuiz(data.quiz);
  const posFail = r.positionRate > MAX_POSITION_RATE;
  const lenFail = r.lengthRate > MAX_LENGTH_RATE;
  const pct = v => (v * 100).toFixed(0) + '%';
  const mark = f => (f ? 'FAIL' : 'ok  ');

  console.log(
    `${tech.padEnd(11)} n=${String(r.n).padEnd(4)}` +
    ` position(${r.positionLetter}) ${pct(r.positionRate).padStart(4)} ${mark(posFail)}` +
    ` | longest ${pct(r.lengthRate).padStart(4)} ${mark(lenFail)}` +
    ` | needs rewrite: ${r.offenders.length}/${r.n}`
  );

  if (LIST && r.offenders.length) {
    for (const o of r.offenders) {
      console.log(`   ${o.pid} Q${o.i + 1}  ${o.reasons.join('; ')}`);
      console.log(`      ${o.q.q.slice(0, 96)}`);
    }
  }
  // A quiz that either heuristic beats is a quiz that can be passed blind
  // (pass mark is ${PASS_MARK}%).
  return posFail || lenFail;
}

// --report writes the work queue to a file so the rewrites can be worked
// through ship by ship instead of scrolling terminal output
function writeReport(techs) {
  const out = ['# Distractor rewrite queue', '',
    'Generated by `node build/lint-quiz.mjs --report`.', '',
    'Each question below can be answered without knowing the material, because the',
    'correct option is much longer than its distractors or a distractor is a',
    'placeholder. A good distractor states a *plausible wrong mental model* at the',
    'same length and confidence as the true answer.', ''];

  let total = 0;
  for (const tech of techs) {
    const data = loadQuiz(tech);
    if (!data) continue;
    const r = auditQuiz(data.quiz);
    total += r.offenders.length;
    out.push(`## ${tech} — ${r.offenders.length}/${r.n} questions`, '');
    out.push(`Always-longest strategy scores **${(r.lengthRate * 100).toFixed(0)}%**; ` +
      `best single letter scores ${(r.positionRate * 100).toFixed(0)}%.`, '');
    for (const o of r.offenders) {
      out.push(`### ${o.pid} Q${o.i + 1} — ${o.reasons.join('; ')}`, '');
      out.push(`**${o.q.q}**`, '');
      o.q.o.forEach((opt, j) => {
        out.push(`- ${j === o.q.a ? '**[correct]**' : '[distractor]'} (${opt.length} chars) ${opt}`);
      });
      out.push('');
    }
  }
  out.splice(9, 0, `**${total} questions need attention.**`, '');
  const file = path.join(ROOT, 'QUIZ-REWRITES.md');
  fs.writeFileSync(file, out.join('\n'));
  console.log(`\nwrote ${path.basename(file)} — ${total} questions queued for rewriting`);
}

function main() {
  const techs = only.length ? only
    : JSON.parse(fs.readFileSync(path.join(ROOT, 'registry.json'), 'utf8')).techs.map(t => t.id);

  console.log(`quiz lint — position tell must be <${pctOf(MAX_POSITION_RATE)}, length tell <${pctOf(MAX_LENGTH_RATE)}, pass mark ${PASS_MARK}%\n`);
  let failed = false;
  let totalOffenders = 0, totalQ = 0;
  for (const t of techs) {
    const data = loadQuiz(t);
    if (!data) { console.log(`${t.padEnd(11)} (no data file)`); continue; }
    const r = auditQuiz(data.quiz);
    totalOffenders += r.offenders.length; totalQ += r.n;
    if (report(t, data)) failed = true;
  }
  console.log(`\n${totalOffenders}/${totalQ} questions still have distractors that give the answer away.`);
  console.log('Shuffling fixes position; only rewriting the distractors fixes length.');
  if (args.includes('--report')) writeReport(techs);
  else if (!LIST) console.log('Run with --list to see them, or --report to write QUIZ-REWRITES.md.');
  if (failed && STRICT) process.exit(1);
}
function pctOf(v) { return (v * 100).toFixed(0) + '%'; }

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1].endsWith('lint-quiz.mjs')) main();
